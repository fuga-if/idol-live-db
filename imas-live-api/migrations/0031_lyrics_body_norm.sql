-- 0031: 歌詞検索の表記ゆれ吸収用に、正規化した本文を持つ。
--
-- 「つばさ」で検索しても「ツバサ」の曲が出ない、という取りこぼしがあった。
-- 実データで数えると効き目が大きい:
--     つばさ    3曲 → 20曲     きらめき  52曲 → 98曲
--     ツバサ   17曲 → 20曲     キラメキ  37曲 → 98曲
--
-- ⚠️ 正規化は **1文字 → 1文字の変換だけ** に限る。
--    検索は body_norm に対して instr で位置を求め、その位置で **body から** 窓を切る。
--    長さの変わる変換 (半角濁点カナ ﾂﾞ → ヅ 等) を入れると位置がズレてスニペットが壊れる。
--    今の実装が lower() (ASCII のみ・長さ不変) に依存しているのと同じ理屈。
--
-- 内容: ひらがな → カタカナ、英字は小文字、全角英数は半角。
--       漢字は対象外 (「翼」と「つばさ」は読みが要るので正規化では届かない)。
--       漢字の揺れは検索側の OR 指定 (翼|つばさ) で扱う。
--
-- backfill は SQL では書けない (SQLite に かな変換が無い) ので、
-- tools/lyrics/backfill_body_norm.py が埋める。以降は PUT が body と同時に書く。

ALTER TABLE song_lyrics ADD COLUMN body_norm TEXT NOT NULL DEFAULT '';
