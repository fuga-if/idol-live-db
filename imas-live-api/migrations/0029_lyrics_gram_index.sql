-- 0029: 歌詞検索の転置インデックス (1-gram / 2-gram)。
--
-- 目的:
--   `body LIKE '%q%'` は先頭ワイルドカードなので索引が効かず、1検索あたり
--   song_lyrics を全走査する (2,291行)。D1 無料枠は 500万行/日なので
--   1日あたり約 2,180 検索が天井になっていた。
--   gram で候補を絞れば、よくある検索 (「光るよ」等) は十数行で済む。
--
-- なぜ posting を1行に詰めるか:
--   (gram, song_id) を1行ずつ持つ正規形だと 123万行になる。D1 無料枠の
--   **書き込みは 10万行/日**なので、そもそも投入しきれない。
--   gram 1つ = 1行 (2,846 + 64,225 = 67,071行) なら1日で入る。
--   posting は改行区切りの song_id。song_id に改行は入らない。
--
-- なぜ 3-gram 以上を作らないか:
--   2-gram まであれば「AB」「BC」の AND で候補を絞れる。長いクエリほど
--   gram が増えて候補が減るので、絞り込みは自然に強くなる。
--   種類を増やすと行数が跳ね上がって投入できない。
--
-- ⚠️ このインデックスは**近似**であって答えではない。
--   1. 2-gram の AND には偽陽性がある (「ABCD」の各 gram が別々の場所にある曲)。
--   2. 歌詞が更新されてから再構築するまでの間はズレる。
--   どちらも routes/lyrics.ts が候補に対して body LIKE で**必ず検証する**ので、
--   誤ってヒットすることはない。ズレは「出るはずの曲が出ない」側にしか倒れない。
--   再構築は tools/lyrics/build_gram_index.py。

CREATE TABLE lyrics_gram_index (
  -- 1文字 または 2文字。歌詞本文から取った素の部分文字列 (正規化しない)。
  gram TEXT PRIMARY KEY,
  -- その gram を含む song_id を "\n" 区切りで並べたもの。
  song_ids TEXT NOT NULL
) WITHOUT ROWID;
