import Foundation

/// 歌詞タブ (= コールガイド) を画面に出してよいか。
///
/// 歌詞の掲載には JASRAC の許諾が要る。**2026-08-05 申請 / 2026-08 認可**で
/// 許諾番号 `J260943703` (非商用配信・ストリーム形式) を取得済みなので、機能は開いている。
///
/// 許諾の範囲はこの 2 つ。どちらも外すと許諾外になる:
///
/// - **ストリーム形式。** 端末に歌詞を残さない。`LyricsAPI` は 1 リクエスト 1 曲で、
///   応答に `Cache-Control: no-store` が付く。まとめ取りの口を作らないこと。
/// - **許諾マークと許諾番号の掲示。** `JASRACLicense` を参照。
///
/// **曲数の上限は無い。** 許諾書には「ご利用曲数 100曲まで」とあるが、JASRAC の
/// 許諾情報では「同時利用曲数」が未設定で、非商用配信は使用料表の
/// 「以後10曲まで毎に加算する額」が「なし」= 曲数で額が変わらない。
/// 何曲公開するかはサーバの `song_lyrics.status` だけが決める。
///
/// 許諾期間は 2026年8月〜2027年7月 (以降自動更新)。
enum LyricsFeature {
    static var isAvailable: Bool { true }
}

/// JASRAC 許諾の掲示物。許諾条件に「許諾マークをトップページに掲載し、その下に
/// 許諾番号を表記する」とあるので、番号の字面をここ 1 箇所に置いて画面から参照する。
enum JASRACLicense {
    /// 非商用配信の許諾番号は英字1文字 + 数字9桁の10桁。
    static let number = "J260943703"

    /// 掲示に使う表記。許諾書の指定は「JASRAC許諾第****************号」。
    static let notice = "JASRAC許諾第\(number)号"
}
